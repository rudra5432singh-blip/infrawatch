// Seeded pseudo-random offset so multiple projects in the same district don't sit on top of each other
function getDeterministicOffset(str, scale = 0.08) {
  let hash = 0;
  for (let i = 0; i < str.length; i++) {
    hash = (hash << 5) - hash + str.charCodeAt(i);
    hash |= 0;
  }
  const x = Math.sin(hash) * scale;
  const y = Math.cos(hash * 1.5) * scale;
  return [x, y];
}

/**
 * Returns [latitude, longitude] for any project object.
 * Checks district first, then state centroid, then India national center.
 * Applies deterministic jitter based on project ID / code and strictly clamps within Indian land borders.
 */
export function getProjectCoordinates(project) {
  if (!project) return [22.9734, 78.6569];

  const key = String(project.id || project.project_id || project.project_code || project.project_name || '0');
  const [latOffset, lngOffset] = getDeterministicOffset(key, 0.04);

  let rawLat = 22.9734;
  let rawLng = 78.6569;

  // 1. Try District
  if (project.district && DISTRICT_COORDINATES[project.district]) {
    const [baseLat, baseLng] = DISTRICT_COORDINATES[project.district];
    rawLat = baseLat + latOffset;
    rawLng = baseLng + lngOffset;
  }
  // 2. Try matching district partially or in project name
  else if (project.district) {
    let matched = false;
    for (const [dist, coords] of Object.entries(DISTRICT_COORDINATES)) {
      if (project.district.toLowerCase().includes(dist.toLowerCase())) {
        rawLat = coords[0] + latOffset;
        rawLng = coords[1] + lngOffset;
        matched = true;
        break;
      }
    }
    if (!matched && project.state && STATE_COORDINATES[project.state]) {
      const [baseLat, baseLng] = STATE_COORDINATES[project.state];
      const [stLatOffset, stLngOffset] = getDeterministicOffset(key, 0.2);
      rawLat = baseLat + stLatOffset;
      rawLng = baseLng + stLngOffset;
    }
  }
  // 3. Try State Centroid
  else if (project.state && STATE_COORDINATES[project.state]) {
    const [baseLat, baseLng] = STATE_COORDINATES[project.state];
    const [stLatOffset, stLngOffset] = getDeterministicOffset(key, 0.2);
    rawLat = baseLat + stLatOffset;
    rawLng = baseLng + stLngOffset;
  }
  // 4. Try matching state in project name
  else if (project.project_name || project.name) {
    const pName = (project.project_name || project.name || '').toLowerCase();
    let matched = false;
    for (const [st, coords] of Object.entries(STATE_COORDINATES)) {
      if (pName.includes(st.toLowerCase())) {
        const [stLatOffset, stLngOffset] = getDeterministicOffset(key, 0.2);
        rawLat = coords[0] + stLatOffset;
        rawLng = coords[1] + stLngOffset;
        matched = true;
        break;
      }
    }
    if (!matched) {
      const [inLatOffset, inLngOffset] = getDeterministicOffset(key, 0.8);
      rawLat = 22.9734 + inLatOffset;
      rawLng = 78.6569 + inLngOffset;
    }
  }
  // 5. Fallback: Center of India
  else {
    const [inLatOffset, inLngOffset] = getDeterministicOffset(key, 0.8);
    rawLat = 22.9734 + inLatOffset;
    rawLng = 78.6569 + inLngOffset;
  }

  // Strict India Mainland Boundary Clamping (prevents any coordinate drifting into ocean or outside territory)
  let lat = rawLat;
  let lng = rawLng;

  if (lat < 8.4) lat = 8.4 + Math.abs(latOffset) * 0.5;
  if (lat > 35.5) lat = 35.5 - Math.abs(latOffset) * 0.5;
  if (lng < 69.2) lng = 69.2 + Math.abs(lngOffset) * 0.5;
  if (lng > 96.0) lng = 96.0 - Math.abs(lngOffset) * 0.5;

  return [lat, lng];
}
